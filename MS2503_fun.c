#include <stdio.h>
#include <stdlib.h>
#include <time.h>
#include <string.h>

#include "MS2503_fun.h"

static unsigned long long random_state = 1ULL;
static int active_host_count = 0;

static Port test_processor_ports[MAX_HOSTES];
static Port lll_upper_ports[MAX_HOSTES];
static Port lll_lower_ports[MAX_HOSTES];
static Port lan_ports[MAX_HOSTES];
static HostInfo hosts[MAX_HOSTES];

static int total_packets_sent;
static int total_packets_received;
static int total_collisions;

int RandomNumberGenerator(void)
{
    random_state = (RANG_MULTIPLIR * random_state + RANG_INCREMENT) %
                   RANG_MODULUS;
    return (int)((random_state >> 16) & 0x7fffffffUL);
}

int initRandomSeed(unsigned long seed)
{
    random_state = seed == 0UL ? 1ULL : (unsigned long long)seed;
    return 0;
}

void ArrayReset(Port *port)
{
    if (port != NULL)
        memset(port, 0, sizeof(*port));
}

void FullReset(int n_host)
{
    int host_id;

    active_host_count = n_host;
    total_packets_sent = 0;
    total_packets_received = 0;
    total_collisions = 0;

    for (host_id = 0; host_id < MAX_HOSTES; ++host_id) {
        ArrayReset(&test_processor_ports[host_id]);
        ArrayReset(&lll_upper_ports[host_id]);
        ArrayReset(&lll_lower_ports[host_id]);
        ArrayReset(&lan_ports[host_id]);
        hosts[host_id].host_id = host_id;
        hosts[host_id].network_address = 7;
        hosts[host_id].machine_address = host_id;
        hosts[host_id].smac = (char)('A' + host_id);
    }
}

void ResetData(int host_id)
{
    if (host_id >= 0 && host_id < MAX_HOSTES)
        ArrayReset(&test_processor_ports[host_id]);
}

void ResetHost(int host_id)
{
    if (host_id >= 0 && host_id < MAX_HOSTES) {
        ArrayReset(&lll_upper_ports[host_id]);
        ArrayReset(&lll_lower_ports[host_id]);
        ArrayReset(&lan_ports[host_id]);
    }
}

int Probability(int percentage)
{
    int threshold;

    if (percentage <= 0)
        return 0;
    if (percentage >= 100)
        return 1;
    threshold = (PROBABILITY_RANGE * percentage) / 100;
    return (RandomNumberGenerator() % PROBABILITY_RANGE) < threshold;
}

void GenerateBytes(unsigned char packet[BUFFER_SIZE], int start_index,
                   int end_index)
{
    int index;

    if (packet == NULL || start_index < 0 || end_index >= BUFFER_SIZE ||
        start_index > end_index)
        return;

    for (index = start_index; index <= end_index; ++index)
        packet[index] = (unsigned char)('a' + RandomNumberGenerator() % 26);
}

void GenerateHost(int n_host)
{
    int host_id;

    if (n_host < MIN_HOSTS || n_host > MAX_HOSTES)
        return;
    active_host_count = n_host;
    for (host_id = 0; host_id < n_host; ++host_id) {
        hosts[host_id].host_id = host_id;
        hosts[host_id].network_address = 7;
        hosts[host_id].machine_address = host_id;
        hosts[host_id].smac = (char)('A' + host_id);
    }
}

static void GenerateHeader(unsigned char packet[BUFFER_SIZE], int sender_id,
                           int receiver_id, int byte_count)
{
    packet[0] = (unsigned char)sender_id;
    packet[1] = (unsigned char)hosts[sender_id].smac;
    packet[2] = (unsigned char)hosts[sender_id].network_address;
    packet[3] = (unsigned char)receiver_id;
    packet[4] = (unsigned char)hosts[receiver_id].smac;
    packet[5] = (unsigned char)byte_count;
}

void GenerateData(int host_id)
{
    unsigned char packet[BUFFER_SIZE] = {0};
    int receiver_id;
    int byte_count;
    int index;

    if (host_id < 0 || host_id >= active_host_count)
        return;

    receiver_id = RandomNumberGenerator() % active_host_count;
    if (receiver_id == host_id)
        receiver_id = (receiver_id + 1) % active_host_count;

    byte_count = PACKET_HEADER_BYTES +
                 MIN_DATA_BYTES +
                 RandomNumberGenerator() % (MAX_DATA_BYTES - MIN_DATA_BYTES + 1);
    GenerateHeader(packet, host_id, receiver_id, byte_count);
    GenerateBytes(packet, PACKET_HEADER_BYTES, byte_count - 1);

    for (index = 0; index < byte_count; ++index)
        test_processor_ports[host_id].d[0][index + 1] = packet[index];
    test_processor_ports[host_id].d[0][0] = (unsigned char)byte_count;

    printf("Data generated by host %d for host %d\n", host_id, receiver_id);
    printf("Generating SIP and SMAC header.\n");
    printf("Packet = \"");
    for (index = 0; index < byte_count; ++index) {
        if (index != 0)
            putchar(' ');
        if (index == 1 || index == 4 || index >= PACKET_HEADER_BYTES)
            printf("%c", packet[index]);
        else
            printf("%d", packet[index]);
    }
    printf("\"\n");
}

void SendData(int host_id)
{
    int byte_count;

    if (host_id < 0 || host_id >= active_host_count)
        return;
    byte_count = test_processor_ports[host_id].d[0][0];
    if (byte_count == 0 || lll_upper_ports[host_id].d[0][0] != 0)
        return;
    memcpy(&lll_upper_ports[host_id].d[0][1],
           &test_processor_ports[host_id].d[0][1], (size_t)byte_count);
    lll_upper_ports[host_id].d[0][0] = (unsigned char)byte_count;
    ArrayReset(&test_processor_ports[host_id]);
    ++total_packets_sent;
}

void CopyData(Port *source, Port *destination)
{
    int byte_count;

    if (source == NULL || destination == NULL)
        return;
    byte_count = source->d[0][0];
    if (byte_count <= 0 || byte_count >= BUFFER_SIZE ||
        destination->d[1][0] != 0)
        return;
    memcpy(&destination->d[1][1], &source->d[0][1], (size_t)byte_count);
    destination->d[1][0] = (unsigned char)byte_count;
}

void Connect(Port *source, Port *destination, const char *source_name,
             const char *destination_name)
{
    (void)source_name;
    (void)destination_name;
    if (source == NULL || destination == NULL)
        return;
    if (source->d[0][0] != 0 && destination->d[1][0] == 0) {
        CopyData(source, destination);
        ArrayReset(source);
    }
}

static void MoveToLan(int host_id)
{
    if (host_id < 0 || host_id >= active_host_count)
        return;
    if (lll_upper_ports[host_id].d[0][0] != 0 &&
        lll_lower_ports[host_id].d[1][0] == 0) {
        printf("Connecting TP and LLL of %d\n", host_id);
        printf("Copying LLL-in to LLL-out of %d\n", host_id);
        Connect(&lll_upper_ports[host_id], &lll_lower_ports[host_id],
                "LLL-in", "LLL-out");
    }
    if (lll_lower_ports[host_id].d[1][0] != 0 &&
        lan_ports[host_id].d[0][0] == 0) {
        printf("Connecting LLL and LAN of %d\n", host_id);
        printf("Copying LAN-in to LAN-out of %d\n", host_id);
        memcpy(&lan_ports[host_id].d[0][1],
               &lll_lower_ports[host_id].d[1][1],
               (size_t)lll_lower_ports[host_id].d[1][0]);
        lan_ports[host_id].d[0][0] = lll_lower_ports[host_id].d[1][0];
        ArrayReset(&lll_lower_ports[host_id]);
    }

}

void ConsumeData(int host_id)
{
    if (host_id < 0 || host_id >= active_host_count)
        return;
    if (lan_ports[host_id].d[1][0] != 0 &&
        lll_lower_ports[host_id].d[1][0] == 0) {
        memcpy(&lll_lower_ports[host_id].d[1][1],
               &lan_ports[host_id].d[1][1],
               (size_t)lan_ports[host_id].d[1][0]);
        lll_lower_ports[host_id].d[1][0] = lan_ports[host_id].d[1][0];
        ArrayReset(&lan_ports[host_id]);
    }
}

static void ProcessReceivedPackets(int n_hosts)
{
    int host_id;

    for (host_id = 0; host_id < n_hosts; ++host_id) {
        ConsumeData(host_id);
        IPstrip(host_id);
        if (test_processor_ports[host_id].d[1][0] != 0) {
            printf("TestP%d has received the packet :\n", host_id);
            ShowData(&test_processor_ports[host_id], 1, NULL);
            printf("TestP%d is now processing the data. WAIT !\n", host_id);
            for (int line = 0; line < 20; ++line)
                printf("....................\n");
            ArrayReset(&test_processor_ports[host_id]);
            ++total_packets_received;
        }
    }
}

void IPstrip(int host_id)
{
    int receiver_id;
    Port *lower;

    if (host_id < 0 || host_id >= active_host_count)
        return;
    lower = &lll_lower_ports[host_id];
    if (lower->d[1][0] < PACKET_HEADER_BYTES)
        return;

    receiver_id = lower->d[1][4];
    if (receiver_id == host_id) {
        memcpy(&test_processor_ports[host_id].d[1][1],
               &lower->d[1][1], (size_t)lower->d[1][0]);
        test_processor_ports[host_id].d[1][0] = lower->d[1][0];
    } else {
        printf("Host%d says : \"This packet: is not for me ! I drop it ! \"\n",
               host_id);
    }
    ArrayReset(lower);
}

void ShowData(Port *port, int direction, const char *port_name)
{
    int index;
    int byte_count;

    if (port == NULL || direction < 0 || direction > 1)
        return;
    byte_count = port->d[direction][0];
    if (byte_count == 0)
        return;
    printf("%s\n", port_name == NULL ? "Packet" : port_name);
    printf("__________________________________\n");
    for (index = 1; index <= byte_count; ++index) {
        if (index > 1)
            putchar(' ');
        printf("%u", (unsigned int)port->d[direction][index]);
    }
    putchar('\n');
}

void PrintLine(const char *message, int host_id, int message_type)
{
    (void)host_id;
    (void)message_type;
    printf("%s\n", message == NULL ? "------------------------------------------------------------------------" :
           message);
}

void SendOverLAN(int n_hosts)
{
    int host_id;
    int sender_id = -1;
    int input_count = 0;

    for (host_id = 0; host_id < n_hosts; ++host_id) {
        if (lan_ports[host_id].d[0][0] != 0) {
            ++input_count;
            sender_id = host_id;
        }
    }
    if (input_count == 0)
        return;
    if (input_count > 1) {
        printf("Collision detected on the LAN. Packet information is lost.\n");
        ++total_collisions;
        for (host_id = 0; host_id < n_hosts; ++host_id)
            ArrayReset(&lan_ports[host_id]);
        return;
    }

    for (host_id = 0; host_id < n_hosts; ++host_id) {
        if (host_id != sender_id && lan_ports[host_id].d[1][0] == 0) {
            memcpy(&lan_ports[host_id].d[1][1],
                   &lan_ports[sender_id].d[0][1],
                   (size_t)lan_ports[sender_id].d[0][0]);
            lan_ports[host_id].d[1][0] = lan_ports[sender_id].d[0][0];
        }
    }
    ArrayReset(&lan_ports[sender_id]);
    printf("Copied packet to LLL of all hosts\n");
}

void RunNW_Simulation(void)
{
    int n_hosts;
    int iteration = 1;
    int host_id;
    int generated_packets;
    char response[16];

    printf("Enter the number of hosts (3 to 26): ");
    if (scanf("%d", &n_hosts) != 1 ||
        n_hosts < MIN_HOSTS || n_hosts > MAX_HOSTES) {
        printf("ERROR: Number of hosts must be between 3 and 26.\n");
        return;
    }

    initRandomSeed((unsigned long)time(NULL));
    FullReset(n_hosts);
    GenerateHost(n_hosts);

    for (;;) {
        PrintLine(NULL, 0, 0);
        printf("ITERATION NO. : %d\n", iteration);
        printf("--------------------\n");
        ProcessReceivedPackets(n_hosts);
        generated_packets = 0;

        for (host_id = 0; host_id < n_hosts; ++host_id) {
            if (Probability(10)) {
                GenerateData(host_id);
                ++generated_packets;
            }
            SendData(host_id);
        }

        if (generated_packets != 0)
            printf("\n******* Sending data over the LAN *******\n\n");

        for (host_id = 0; host_id < n_hosts; ++host_id) {
            if (lll_upper_ports[host_id].d[0][0] != 0)
                printf("Receiver = %d\n",
                       lll_upper_ports[host_id].d[0][4]);
            MoveToLan(host_id);
        }
        if (generated_packets != 0) {
            for (host_id = 0; host_id < n_hosts; ++host_id)
                printf(" connecting LAN and LLL of %d\n", host_id);
        }
        SendOverLAN(n_hosts);

        printf("\nENTER Q to quit; ANY OTHER CHARACTER to continue : ");
        if (scanf("%15s", response) != 1 ||
            response[0] == 'Q' || response[0] == 'q')
            break;
        ++iteration;
    }

    printf("\nPackets sent: %d\nPackets received: %d\nCollisions: %d\n",
           total_packets_sent, total_packets_received, total_collisions);
}
